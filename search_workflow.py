#!/usr/bin/env python3
"""
search_engine.py

A unified GraphRAG search CLI tool using Microsoft GraphRAG with LiteLLM
and Google Gemini 2.5 Flash Lite model.

This script implements four GraphRAG search methods:
1. Global Search - Map-reduce search over community reports
2. Local Search - Contextual search over entities, relationships, covariates, and text units
3. DRIFT Search - Dynamic Reasoning and Information Traversal Search
4. Basic Search - Standard vector-based RAG search over text unit chunks

Requirements:
- graphrag
- litellm
- pandas
- pyarrow
- lancedb

Usage Examples:
  python search_engine.py --mode global --query "What are the major themes in the dataset?"
  python search_engine.py --mode local --query "Tell me about Entity X"
  python search_engine.py --mode drift --query "How does Component A interact with Component B?"
  python search_engine.py --mode basic --query "Find references to project milestones"
"""

